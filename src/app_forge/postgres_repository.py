"""SQLAlchemy-backed PostgreSQL database and generic repository primitives.

Install the optional postgres extra before using this module. No connection is
opened until the engine is first used; schema creation is always explicit.
"""
from __future__ import annotations

from contextlib import contextmanager
import math
from typing import Any, Generic, Iterator, TypeVar

try:
    from sqlalchemy import Engine, create_engine, func, select
    from sqlalchemy.engine import make_url
    from sqlalchemy.orm import DeclarativeBase, Session, sessionmaker
except ImportError as exc:  # pragma: no cover - dependency isolation
    raise ImportError(
        "PostgreSQL repository support requires the optional 'postgres' extra "
        "(SQLAlchemy >= 2.0 and psycopg >= 3.2)."
    ) from exc


ModelT = TypeVar("ModelT", bound=DeclarativeBase)


class RepositoryError(RuntimeError):
    """Base error for repository operations."""


class RecordNotFound(RepositoryError, LookupError):
    """Raised when an update or required lookup targets a missing row."""


class PostgresDatabase:
    """Own a pooled PostgreSQL engine and short-lived ORM sessions.

    The URL must use SQLAlchemy's PostgreSQL dialect. pool_pre_ping is always
    enabled to discard stale connections after database restarts or network drops.
    Credentials are retained only in SQLAlchemy's URL object and are never included
    in error messages generated by this adapter.
    """

    def __init__(
        self,
        url: str,
        *,
        echo: bool = False,
        pool_size: int = 5,
        max_overflow: int = 10,
        pool_timeout: float = 30.0,
        pool_recycle: int = 1800,
    ) -> None:
        if not isinstance(url, str) or not url.strip():
            raise ValueError("url must be a non-empty PostgreSQL SQLAlchemy URL")
        try:
            parsed = make_url(url)
        except Exception as exc:
            raise ValueError("url must be a valid PostgreSQL SQLAlchemy URL") from exc
        if parsed.get_backend_name() != "postgresql":
            raise ValueError("url must use the PostgreSQL SQLAlchemy dialect")
        if not parsed.database:
            raise ValueError("PostgreSQL URL must name a database")
        if isinstance(pool_size, bool) or not isinstance(pool_size, int) or pool_size < 1:
            raise ValueError("pool_size must be a positive integer")
        if isinstance(max_overflow, bool) or not isinstance(max_overflow, int) or max_overflow < 0:
            raise ValueError("max_overflow must be a non-negative integer")
        if (
            isinstance(pool_timeout, bool)
            or not isinstance(pool_timeout, (int, float))
            or not math.isfinite(pool_timeout)
            or pool_timeout <= 0
        ):
            raise ValueError("pool_timeout must be a finite positive number")
        if isinstance(pool_recycle, bool) or not isinstance(pool_recycle, int) or pool_recycle < -1:
            raise ValueError("pool_recycle must be an integer greater than or equal to -1")

        self.url = parsed
        self.engine: Engine = create_engine(
            parsed,
            echo=bool(echo),
            pool_pre_ping=True,
            pool_size=pool_size,
            max_overflow=max_overflow,
            pool_timeout=float(pool_timeout),
            pool_recycle=pool_recycle,
        )
        self._sessions = sessionmaker(
            bind=self.engine, class_=Session, expire_on_commit=False, autoflush=True
        )

    def create_schema(self, base: type[DeclarativeBase]) -> None:
        """Create missing tables explicitly; never called implicitly."""
        base.metadata.create_all(self.engine)

    @contextmanager
    def session(self) -> Iterator[Session]:
        """Yield a session and close it on success or failure."""
        session = self._sessions()
        try:
            yield session
        finally:
            session.close()

    @contextmanager
    def transaction(self) -> Iterator[Session]:
        """Run a unit of work atomically and roll it back on exceptions."""
        with self.session() as session:
            with session.begin():
                yield session

    def dispose(self) -> None:
        """Close all pooled connections."""
        self.engine.dispose()

    def __enter__(self) -> PostgresDatabase:
        return self

    def __exit__(self, *_args: Any) -> None:
        self.dispose()


class PostgresRepository(Generic[ModelT]):
    """Typed CRUD repository for one SQLAlchemy declarative model."""

    def __init__(self, database: PostgresDatabase, model: type[ModelT]) -> None:
        if not hasattr(model, "__table__"):
            raise TypeError("model must be a SQLAlchemy declarative model")
        self.database = database
        self.model = model
        primary_keys = tuple(model.__mapper__.primary_key)
        if len(primary_keys) != 1:
            raise ValueError("repository models must have exactly one primary-key column")
        primary_key_name = primary_keys[0].key
        if primary_key_name is None:
            raise ValueError("repository primary-key column must have a name")
        self._primary_key: str = primary_key_name

    def add(self, **values: Any) -> ModelT:
        with self.database.transaction() as session:
            record = self.model(**values)
            session.add(record)
            session.flush()
            session.refresh(record)
            return record

    def get(self, identity: Any) -> ModelT | None:
        with self.database.session() as session:
            return session.get(self.model, identity)

    def require(self, identity: Any) -> ModelT:
        record = self.get(identity)
        if record is None:
            raise RecordNotFound(f"{self.model.__name__} {identity!r} was not found")
        return record

    def list(
        self,
        *,
        filters: dict[str, Any] | None = None,
        order_by: str | None = None,
        descending: bool = False,
        limit: int = 100,
        offset: int = 0,
    ) -> list[ModelT]:
        if isinstance(limit, bool) or not isinstance(limit, int) or not 1 <= limit <= 1000:
            raise ValueError("limit must be an integer from 1 to 1000")
        if isinstance(offset, bool) or not isinstance(offset, int) or offset < 0:
            raise ValueError("offset must be a non-negative integer")
        statement = select(self.model)
        for name, value in (filters or {}).items():
            column = getattr(self.model, name, None)
            if column is None or name.startswith("_"):
                raise ValueError(f"unknown filter field: {name!r}")
            statement = statement.where(column == value)
        sort_name = self._primary_key if order_by is None else order_by
        sort_column = getattr(self.model, sort_name, None)
        if sort_column is None or sort_name.startswith("_"):
            raise ValueError(f"unknown order field: {sort_name!r}")
        statement = statement.order_by(
            sort_column.desc() if descending else sort_column.asc()
        ).limit(limit).offset(offset)
        with self.database.session() as session:
            return list(session.scalars(statement).all())

    def count(self, *, filters: dict[str, Any] | None = None) -> int:
        statement = select(func.count()).select_from(self.model)
        for name, value in (filters or {}).items():
            column = getattr(self.model, name, None)
            if column is None or name.startswith("_"):
                raise ValueError(f"unknown filter field: {name!r}")
            statement = statement.where(column == value)
        with self.database.session() as session:
            return int(session.scalar(statement) or 0)

    def update(self, identity: Any, **changes: Any) -> ModelT:
        if self._primary_key in changes:
            raise ValueError("primary-key updates are not supported")
        with self.database.transaction() as session:
            record = session.get(self.model, identity)
            if record is None:
                raise RecordNotFound(f"{self.model.__name__} {identity!r} was not found")
            for name, value in changes.items():
                if name.startswith("_") or not hasattr(type(record), name):
                    raise ValueError(f"unknown update field: {name!r}")
                setattr(record, name, value)
            session.flush()
            session.refresh(record)
            return record

    def delete(self, identity: Any) -> bool:
        with self.database.transaction() as session:
            record = session.get(self.model, identity)
            if record is None:
                return False
            session.delete(record)
            return True
